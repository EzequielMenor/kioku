import { parseNote, setFrontmatter } from "../../../src/core/markdown.ts";
import { UNAUTHORIZED_EVENT } from "../api.ts";
import { SendError } from "./queue.ts";
import type { MutationBody, MutationResult, TaskStatus } from "./store.ts";

export function requireDurable(durable: boolean): void {
  if (!durable) throw new Error("No hay almacenamiento persistente disponible; no se puede guardar la edición.");
}

export function materializeTask(text: string, path: string, status: TaskStatus): string {
  if (parseNote(text, path).frontmatterError) throw new Error("Frontmatter YAML inválido: no se modifica");
  return setFrontmatter(text, { status, ...(status === "done" ? {} : { done_at: null }) });
}

/** Adopt only metadata generated by an acknowledged task; never replace the local body or a newer status. */
export function reconcileTaskAcknowledgement(text: string, canonical: string, status: TaskStatus): string {
  const local = parseNote(text, ""), remote = parseNote(canonical, "");
  if (local.frontmatterError || remote.frontmatterError || local.frontmatter.status !== status || remote.frontmatter.status !== status) return text;
  if (status !== "done") return text;
  const timestamp = remote.frontmatter.done_at;
  if (typeof timestamp !== "string") return text;
  return setFrontmatter(text, { done_at: timestamp });
}

export async function sendMobileOperation(body: MutationBody, fetcher: typeof fetch = fetch, unauthorized: () => void = () => { window.dispatchEvent(new Event(UNAUTHORIZED_EVENT)); }): Promise<MutationResult> {
  let response: Response;
  try { response = await fetcher("/api/mobile/operation", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) }); }
  catch (e) { throw new SendError(e instanceof Error ? e.message : "Error de red", true); }
  const data = await response.json().catch(() => ({}));
  if (response.status === 401) unauthorized();
  if (response.status === 409 && data.code === "mobile-conflict" && data.result?.outcome === "conflict" && typeof data.result.path === "string" && typeof data.result.hash === "string") return data.result;
  if (!response.ok) throw new SendError(data.error ?? `Error ${response.status}`, response.status === 401 || response.status === 408 || response.status === 429 || response.status >= 500);
  if (data.outcome !== "applied" || typeof data.path !== "string" || typeof data.hash !== "string" || (data.text !== undefined && typeof data.text !== "string")) throw new SendError("Respuesta inválida del servidor", true);
  return data;
}
